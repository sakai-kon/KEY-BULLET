const SORTED_ENTRIES = [...ENTRIES].sort((a, b) => b[0].length - a[0].length);

export function renderPromptWithFurigana(container: HTMLElement, text: string, enabled: boolean): void {
  if (!enabled) {
    container.textContent = text;
    return;
  }

  const fragment = document.createDocumentFragment();
  let index = 0;
  let plain = '';

  const flushPlain = () => {
    if (plain) {
      fragment.append(document.createTextNode(plain));
      plain = '';
    }
  };

  while (index < text.length) {
    const entry = SORTED_ENTRIES.find(([surface]) => text.startsWith(surface, index));
    if (!entry) {
      const character = String.fromCodePoint(text.codePointAt(index) ?? 0);
      plain += character;
      index += character.length;
      continue;
    }

    flushPlain();
    const [surface, rubyBase, reading] = entry;
    const ruby = document.createElement('ruby');
    ruby.append(document.createTextNode(rubyBase));
    const rt = document.createElement('rt');
    rt.textContent = reading;
    ruby.append(rt);
    fragment.append(ruby);
    const remainder = surface.slice(rubyBase.length);
    if (remainder) fragment.append(document.createTextNode(remainder));
    index += surface.length;
  }

  flushPlain();
  container.replaceChildren(fragment);
}
